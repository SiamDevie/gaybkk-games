const gameSlugs = new Set(GAME_REGISTRY.map((game) => game.slug));
const gameIds = new Set(GAME_REGISTRY.map((game) => game.id));

if (gameSlugs.size !== GAME_REGISTRY.length || gameIds.size !== GAME_REGISTRY.length) {
  throw new Error("Game registry IDs and slugs must be unique.");
}

export function getGameBySlug(slug: string): GameDefinition | undefined {
  return GAME_REGISTRY.find((game) => game.slug === slug);
}
